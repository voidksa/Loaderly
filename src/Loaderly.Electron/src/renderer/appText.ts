export type TextKey = keyof typeof text.en;

export function createText(locale: AppLocale) {
  return (key: TextKey, params: TextParams = {}) => {
    const template = String(text[locale][key] ?? text.en[key]);

    return Object.entries(params).reduce<string>(
      (value, [paramKey, paramValue]) => value.replaceAll(`{${paramKey}}`, String(paramValue)),
      template
    );
  };
}

export function localeLabel(locale: AppLocale): string {
  return locale === 'ar' ? text.ar.arabic : text.en.english;
}

export function themeLabel(themeMode: ThemeMode, locale: AppLocale): string {
  return themeMode === 'dark' ? text[locale].dark : text[locale].light;
}

export function qualityLabel(quality: DownloadQuality, locale: AppLocale = 'en'): string {
  switch (quality) {
    case '2160p':
    case '1440p':
    case '1080p':
    case '720p':
    case '480p':
    case '360p':
      return quality;
    case 'audio':
      return locale === 'ar' ? 'صوت فقط' : 'Audio only';
    case 'best':
      return locale === 'ar' ? 'الأفضل' : 'Best';
  }
}

export function quickCopyLabel(kind: QuickCopyOutputKind, locale: AppLocale): string {
  switch (kind) {
    case QuickCopyOutputKind.Video:
      return text[locale].copyVideo;
    case QuickCopyOutputKind.Image:
      return text[locale].copyImage;
    case QuickCopyOutputKind.Gif:
      return text[locale].copyGif;
    case QuickCopyOutputKind.Snapshot:
      return text[locale].copySnapshot;
    case QuickCopyOutputKind.Audio:
      return locale === 'ar' ? 'نسخ صوت' : 'Copy audio';
  }
}
