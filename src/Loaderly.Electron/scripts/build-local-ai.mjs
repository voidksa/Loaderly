import { spawnSync } from 'node:child_process';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const python=process.env.LOADERLY_AI_BUILD_PYTHON;
if(!python||!existsSync(python))throw new Error('Set LOADERLY_AI_BUILD_PYTHON to the Python 3.10 or 3.11 build environment with local-ai/requirements.txt and PyInstaller installed.');
const result=spawnSync(python,['-m','PyInstaller','--noconfirm','--distpath',resolve(root,'build/local-ai-output'),'--workpath',resolve(root,'build/local-ai-work'),resolve(root,'local-ai/loaderly-ai.spec')],{cwd:root,stdio:'inherit',windowsHide:true});
if(result.status!==0)process.exit(result.status??1);
const built=resolve(root,'build/local-ai-output/loaderly-ai'),target=resolve(root,'build/local-ai');
if(dirname(target)!==resolve(root,'build'))throw new Error('Invalid runtime destination');
rmSync(target,{recursive:true,force:true});
mkdirSync(target,{recursive:true});cpSync(built,target,{recursive:true});
const sourceSha256=createHash('sha256').update(readFileSync(resolve(root,'local-ai/worker.py'))).update(readFileSync(resolve(root,'local-ai/models.json'))).digest('hex');
const licenses=spawnSync(python,[resolve(root,'local-ai/licenses.py'),resolve(target,'licenses')],{cwd:root,stdio:'inherit',windowsHide:true});
if(licenses.status!==0)throw new Error('Could not collect runtime licenses');
writeFileSync(resolve(target,'build.json'),JSON.stringify({schema:1,platform:process.platform,arch:process.arch,python:spawnSync(python,['-c','import sys; print(sys.version.split()[0])'],{encoding:'utf8',windowsHide:true}).stdout.trim(),sourceSha256,engines:['faster-whisper 1.2.1','Demucs 4.0.1']},null,2));
